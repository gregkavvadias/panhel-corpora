# Builds paper/numbers.md: every figure the paper may quote, at full precision, from reanalysis/results.
# Thresholds and exam subsets are recomputed in memory with the stats5 functions on the current
# 27 + 26 lexical features (the archived lexical_thresholds/lexical_subsets CSVs hold the 28-text run).
# So are the lexical robustness rows and token shares (archived lexical_comparisons.csv is the 28-text run).
import sys
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]

def p_apa(p):
    return '< .001' if p < .001 else f'{p:.4f}'

def f4(x):
    return f'{x:.4f}'

def _cmp_line(r, label=None):
    s = f"- {label or r.measure} ({r.version}, {r.subset}): school M = {f4(r.school_M)}, exam M = {f4(r.exam_M)}, " \
        f"diff = {f4(r['diff'])}, g = {f4(r.g)} [{f4(r.g_lo)}, {f4(r.g_hi)}]"
    if pd.notna(r.p_welch):
        s += f", p = {f4(r.p_welch)} ({p_apa(r.p_welch)}), p_MW = {f4(r.p_mw)}"
    if pd.notna(r.get('p_welch_BH')):
        s += f", BH p = {f4(r.p_welch_BH)} ({p_apa(r.p_welch_BH)})"
    return s

def build(results_dir):
    R = Path(results_dir)
    sys.path.insert(0, str(ROOT / 'reanalysis'))
    from corpus import is_exam
    from stats5 import thresholds, subset_rows, compare, tost_welch
    out = ['# Numbers the paper may quote', '',
           'Generated by `paper/tools/numbers_build.py` from `reanalysis/results/`. Do not edit by hand.', '']
    F = pd.read_csv(R / 'lexical_features.csv')
    full = F[F.version == 'full']
    ex = full[full.book.map(is_exam)]; sc = full[~full.book.map(is_exam)]
    out += ['## Corpus', '',
            f'- coursebook texts {len(sc)}; exam texts {len(ex)}; total {len(full)}',
            f"- exam June {int(ex.text.str.endswith('-06').sum())}; exam resit {int(ex.text.str.endswith('-09').sum())}",
            f'- tokens (alphabetic): coursebook total {int(sc.n_tokens.sum())}, mean {f4(sc.n_tokens.mean())}, '
            f'min {int(sc.n_tokens.min())}, max {int(sc.n_tokens.max())}; exam total {int(ex.n_tokens.sum())}, '
            f'mean {f4(ex.n_tokens.mean())}, min {int(ex.n_tokens.min())}, max {int(ex.n_tokens.max())}', '']
    C = pd.read_csv(R / 'difficulty_comparisons.csv')
    out += ['## Primary tests (27 vs 26)', '']
    for _, r in C[C.role == 'primary'].iterrows():
        out.append(_cmp_line(r))
        if r.measure == 'cov5k':
            out.append(f'- cov5k TOST: 90% CI [{f4(r.ci90_lo)}, {f4(r.ci90_hi)}], p_TOST = {f4(r.p_tost)} '
                       f'({p_apa(r.p_tost)}), equivalent within ±2 = {r.equivalent}')
    out += ['', '## Robustness', ''] + [_cmp_line(r) for _, r in C[C.role == 'robustness'].iterrows()]
    out += ['', '## Descriptive measures', ''] + [_cmp_line(r) for _, r in C[C.role == 'descriptive'].iterrows()]
    out += ['', '## Coverage thresholds (group means, full texts)', '']
    for _, r in thresholds(F).iterrows():
        bands = ', '.join(f"{k}k {f4(r[f'cov{k}k'])}" for k in range(1, 10))
        out.append(f'- {r.group}: {bands}; reaches 95% at {r.level_95}k, 98% at {r.level_98}k')
    for k, th in ((5, 95), (6, 98)):
        out.append(f'- texts reaching {th}% at {k}k: coursebook {int((sc[f"cov{k}k"] >= th).sum())}/{len(sc)}, '
                   f'exam {int((ex[f"cov{k}k"] >= th).sum())}/{len(ex)}')
    out += ['', '## Exam subsets (cov5k, conc_tok vs all 27 coursebook texts)', '']
    for _, r in subset_rows(sc, ex).iterrows():
        s = f"- {r.subset} (n = {r.n_exam}) {r.measure}: g = {f4(r.g)} [{f4(r.g_lo)}, {f4(r.g_hi)}], " \
            f"diff = {f4(r['diff'])}, p = {f4(r.p_welch)}, BH p = {f4(r.p_welch_BH)}"
        if r.measure == 'cov5k':
            s += f", 90% CI [{f4(r.ci90_lo)}, {f4(r.ci90_hi)}], equivalent = {r.equivalent}"
        out.append(s)
    out += ['', '## Lexical robustness (27 vs 26)', '']
    sc360 = F[(F.version == 'first360') & ~F.book.map(is_exam)]
    for m, v, school in (('cov5k', 'first360', sc360), ('conc_tok', 'first360', sc360),
                         ('cov5k_propn_known', 'full', sc), ('cov5k_base_only', 'full', sc), ('conc_type', 'full', sc)):
        r = compare(school[m].to_numpy(), ex[m].to_numpy())
        s = f"- {m} ({v}, all): school M = {f4(r['school_M'])}, exam M = {f4(r['exam_M'])}, diff = {f4(r['diff'])}, "             f"g = {f4(r['g'])} [{f4(r['g_lo'])}, {f4(r['g_hi'])}], p = {f4(r['p_welch'])} ({p_apa(r['p_welch'])})"
        if m.startswith('cov5k'):
            t = tost_welch(school[m].to_numpy(), ex[m].to_numpy(), 2)
            s += f", 90% CI [{f4(t['ci90_lo'])}, {f4(t['ci90_hi'])}], p_TOST = {f4(t['p_tost'])}, equivalent = {t['equivalent']}"
        out.append(s)
    out.append('- token shares (mean % of tokens, full texts): ' + '; '.join(
        f'{c} coursebook {f4(sc[c].mean())}, exam {f4(ex[c].mean())}' for c in ('propn_pct', 'supp_pct', 'offlist_pct')))
    V = pd.read_csv(R / 'difficulty_validation.csv')
    out += ['', '## Validation against Coh-Metrix (Spearman rho [95% CI])', '']
    for m, g in V.groupby(['measure', 'cohmetrix'], sort=False):
        out.append(f'- {m[0]} vs {m[1]}: ' + '; '.join(f"{r.group} {f4(r.rho)} [{f4(r.lo)}, {f4(r.hi)}] (n = {r.n})"
                                                      for r in g.itertuples()))
    S = pd.read_csv(R / 'separation_summary.csv')
    out += ['', '## Separation (elastic net, nested LOOCV)', '']
    for r in S.itertuples():
        out.append(f'- {r.version}: accuracy {f4(r.accuracy)}, balanced accuracy {f4(r.balanced_accuracy)}, '
                   f'AUC {f4(r.auc)}, permutation p {f4(r.perm_p)} (n_perm = {r.n_perm}), C {r.C}, l1_ratio {r.l1_ratio}')
    P = pd.read_csv(R / 'separation_features.csv')
    for v, g in P.groupby('version'):
        g = g.assign(a=g.coef.abs()).sort_values('a', ascending=False)
        out.append(f'- {v} coefficients: ' + '; '.join(f'{r.feature} {f4(r.coef)} ({f4(r.selected_pct)}%)'
                                                        for r in g.itertuples()))
        out.append(f'- {v}: {int((g.selected_pct >= 80).sum())} of {len(g)} measures selected in >= 80% of folds')
    out += ['', '## Genre', '']
    G = pd.read_csv(R / 'genre_composition.csv')
    out += ['- composition: ' + '; '.join(f'{r.fine} school {r.school} exam {r.exam}' for r in G.itertuples())]
    fi = pd.read_csv(R / 'genre_fisher.csv').iloc[0]
    out.append(f'- Fisher: narrative school {fi.narrative_school}, exam {fi.narrative_exam}; non-narrative school '
               f'{fi.nonnarrative_school}, exam {fi.nonnarrative_exam}; p = {f4(fi.p)}; OR = {fi.odds_ratio}, '
               f'95% CI [{f4(fi.or_lo)}, {fi.or_hi}]')
    for _, r in pd.read_csv(R / 'genre_within.csv').iterrows():
        out.append(f'- within non-narrative {r.measure} (n = {r.n_school}, {r.n_exam}): school M = {f4(r.school_M)}, '
                   f'exam M = {f4(r.exam_M)}, g = {f4(r.g)} [{f4(r.g_lo)}, {f4(r.g_hi)}], p = {f4(r.p_welch)}, '
                   f'BH p = {f4(r.p_welch_BH)}; all-text g = {f4(r.g_all)} [{f4(r.g_all_lo)}, {f4(r.g_all_hi)}]')
    for _, r in pd.read_csv(R / 'genre_regression.csv').iterrows():
        out.append(f'- regression {r.measure}: exam coef unadjusted {f4(r.coef_unadj)}, adjusted {f4(r.coef_adj)} '
                   f'[{f4(r.adj_lo)}, {f4(r.adj_hi)}], change {f4(r['pct_change'])}%')
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    (ROOT / 'paper' / 'numbers.md').write_text(build(ROOT / 'reanalysis' / 'results'), encoding='utf-8')
    print('wrote paper/numbers.md')
